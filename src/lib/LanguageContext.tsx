const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  isHindi: false,
  isBengali: false,
  isOdia: false,
  t: (key: string, fallback?: string) => fallback || key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    try {
      const saved = localStorage.getItem('boutique_app_language');
      if (saved === 'hi' || saved === 'en' || saved === 'bn' || saved === 'or') return saved as AppLanguage;
    } catch {
      // ignore
    }
    return 'en'; // Default is English
  });

  const setLanguage = (lang: AppLanguage) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('boutique_app_language', lang);
    } catch {
      // ignore
    }
  };

  const isHindi = language === 'hi';
  const isBengali = language === 'bn';
  const isOdia = language === 'or';

  const t = (key: string, fallback?: string): string => {
    const dict = translations[language];
    if (dict && dict[key]) {
      return dict[key];
    }
    const defaultDict = translations.en;
    if (defaultDict && defaultDict[key]) {
      return defaultDict[key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, isHindi, isBengali, isOdia, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
